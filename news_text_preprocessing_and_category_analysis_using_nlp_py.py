def remove_noise(tokens):

    cleaned_tokens = []

    for token in tokens:

        # Remove URLs
        if re.search(
            r"https?://|www\.",
            token
        ):
            continue

        # Keep alphabetic words only
        if not token.isalpha():
            continue

        # Remove very short tokens
        if len(token) <= 1:
            continue

        cleaned_tokens.append(token)

    return cleaned_tokens


data["tokens"] = data[
    "tokens"
].apply(
    remove_noise
)

print("\nNoise removal completed.")

