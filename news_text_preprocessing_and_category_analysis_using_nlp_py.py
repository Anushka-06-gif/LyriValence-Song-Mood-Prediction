"""21. POS TAGGING"""

def get_wordnet_pos(tag):

    if tag.startswith("J"):

        return wordnet.ADJ

    elif tag.startswith("V"):

        return wordnet.VERB

    elif tag.startswith("N"):

        return wordnet.NOUN

    elif tag.startswith("R"):

        return wordnet.ADV

    else:

        return wordnet.NOUN


def get_pos_tags(tokens):

    tagged_tokens = pos_tag(tokens)

    return [
        (
            word,
            get_wordnet_pos(tag)
        )
        for word, tag in tagged_tokens
    ]


print("\nApplying POS tagging...")

